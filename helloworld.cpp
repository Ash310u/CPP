#include <iostream>

int main() {
    // std = standard:: 
    // cout = charOutput 
    // << = output operator
    // endl = end line (basically \n)
    std::cout << "Hello World" << std::endl;
    
    // with \n
    std::cout << "Hello World" << '\n';

    // without endl = without \n)
    std::cout << "Hello World";

    return 0;
}